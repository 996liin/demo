static unsigned char CamLensSelfCheck(void)
{
	static unsigned char ucCamZoomCheckStatus = 0;
	static unsigned char ucCamZoomCheckCnt = 0;
	static unsigned char ucCamZoomCheckFinish = 0;

	static unsigned char ucCamFocusCheckStatus = 0;
	static unsigned char ucCamFocusCheckCnt = 0;
	static unsigned char ucCamFocusCheckFinish = 0;
	
	static unsigned short usCamZoomTeleAD = 0;
	static unsigned short usCamZoomWideAD = 0;
	static unsigned short usCamFocusNearAD = 0;
	static unsigned short usCamFocusFarAD = 0;
	static unsigned short usData1 = 0, usData2 = 0;
	
	if(0 == ucCamZoomCheckStatus)
	{
		LensLaser(1);
		
		usData1 = ps_ADC->GetCamZoomAD();
		ps_Systick->delay_ms(400);
		usData2 = ps_ADC->GetCamZoomAD();
		
		if(abs(usData1 - usData2) <= 50)
		{
			ucCamZoomCheckCnt++;
			if(ucCamZoomCheckCnt >= 3)
			{
				ucCamZoomCheckCnt = 0;
				ucCamZoomCheckStatus = 1;
				LensLaser(3);
				usCamZoomTeleAD = ps_ADC->GetCamZoomAD();
			}
		}
	}
	else if(1 == ucCamZoomCheckStatus)
	{
		LensLaser(2);
		
		usData1 = ps_ADC->GetCamZoomAD();
		ps_Systick->delay_ms(400);
		usData2 = ps_ADC->GetCamZoomAD();
		
		if(abs(usData1 - usData2) <= 50)
		{
			ucCamZoomCheckCnt++;
			if(ucCamZoomCheckCnt >= 3)
			{
				ucCamZoomCheckCnt = 0;
				ucCamZoomCheckStatus = 2;
				LensLaser(3);
				usCamZoomWideAD = ps_ADC->GetCamZoomAD();
			}
		}
	}
	else if(2 == ucCamZoomCheckStatus)
	{
		if(abs(usCamZoomWideAD - usCamZoomTeleAD) > 600)
		{
			if(usCamZoomWideAD > usCamZoomTeleAD)
			{
				ucCamZoomSelfCheckDir = 1;
				usCamZoomADMax = usCamZoomWideAD;
				usCamZoomADMin = usCamZoomTeleAD;
			}
			else
			{
				ucCamZoomSelfCheckDir = 0;
				usCamZoomADMax = usCamZoomTeleAD;
				usCamZoomADMin = usCamZoomWideAD;
			}
			ucCamZoomCheckFinish = 1;
		}
		else
		{
			ucCamZoomCheckFinish = 0;
		}	
		ucCamZoomCheckStatus = 3;
	}
	if(3 == ucCamZoomCheckStatus)
	{
		unsigned char ucSelfCheckStatus = 0;
		
		if(ucCamZoomCheckFinish)
		{
			ucSelfCheckStatus |= 1;
		}
		ucCamZoomCheckStatus = 0;
		return ucSelfCheckStatus;
	}
	else
	{
		return 0;
	}
}
