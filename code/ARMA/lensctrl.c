static void LocatCamZoomAD(unsigned short usTargetZoom)
{
	if( usTargetZoom >= usCamZoomADMax )
	{
		usTargetZoom = usCamZoomADMax;
	}
	else if( usTargetZoom <= usCamZoomADMin )
	{
		usTargetZoom = usCamZoomADMin;
	}
	//unsigned short usCamNowZoom = ps_ADC->GetCamZoomAD();
	
	if(abs(s_Lens.usZoomValue - usTargetZoom) > 15)
	{
		ps_Arr->ucCamZoomArr = 0;
		
		if(usTargetZoom > s_Lens.usZoomValue )
		{
			if(1 == ucCamZoomSelfCheckDir)
			{
				ucCamZoomRunDir = LENSRUN_WIDE;
			}
			else
			{
				ucCamZoomRunDir = LENSRUN_TELE;
			}
		}
		else
		{
			if(1 == ucCamZoomSelfCheckDir)
			{
				ucCamZoomRunDir = LENSRUN_TELE;
			}
			else
			{
				ucCamZoomRunDir = LENSRUN_WIDE;
			}
		}
	}
	else
	{
		ucCamZoomRunDir = LENSRUN_STOP;
		CamZoomStop();
		ucLocatCamZoomFlag = 0;
		ps_Arr->ucCamZoomArr = 1;
	}
	
}
